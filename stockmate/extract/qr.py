"""QR decoding for e-invoice bills.

An Indian e-invoice carries a QR code generated by the Invoice Registration
Portal.  Its contents are a JSON Web Signature in compact form, three
base64url segments joined by dots: a header naming the algorithm, a payload
holding the invoice particulars, and the NIC signature over the first two.

What this module does and does not claim
----------------------------------------
It decodes the payload and reads the fields.  It does not verify the signature,
and ``QRPayload.signature_verified`` is therefore set to False on every path
through this file, with no option to set it otherwise.  Verification would
require NIC's published certificate for the signing key, obtained and pinned
through a channel this prototype does not have, and a signature that is merely
parsed rather than checked is worth nothing at all.  Treating an unverified
payload as proof would be worse than ignoring the QR: it would let anyone who
can print a QR code assert a seller GSTIN and an invoice value that the system
would then believe over the printed paper.

So the decoded payload is used in exactly one way downstream, as a second
witness to be cross-checked against what the OCR read off the face of the bill.
Agreement raises confidence in both readings.  Disagreement is a finding for the
owner to look at.  Neither is evidence about the document's authenticity.

Robustness matters here more than coverage.  Photographs produce no QR far more
often than they produce a bad one, and some suppliers put a plain URL or their
own JSON in the code instead of a JWS.  Every function in this module returns a
value for those cases rather than raising, because a bill that happens to have a
smudged QR must still go through the rest of the pipeline.
"""

from __future__ import annotations

import base64
import binascii
import json
from datetime import date, datetime

import numpy as np

from ..models import QRPayload
from ..money import parse_money

__all__ = ["decode_qr", "parse_einvoice_payload", "read_einvoice_qr"]

#: Field names as the IRP writes them, mapped to the attribute they fill.  The
#: portal has shipped both spellings of a few of these over the years, so each
#: attribute accepts several keys and the first one present wins.
_FIELD_KEYS: dict[str, tuple[str, ...]] = {
    "seller_gstin": ("SellerGstin", "sellerGstin", "SellerGSTIN", "sgstin"),
    "buyer_gstin": ("BuyerGstin", "buyerGstin", "BuyerGSTIN", "bgstin"),
    "doc_number": ("DocNo", "docNo", "DocNumber", "docno"),
    "irn": ("Irn", "irn", "IRN"),
}

_DATE_KEYS = ("DocDt", "docDt", "DocDate", "docdt")
_TOTAL_KEYS = ("TotInvVal", "totInvVal", "TotalInvVal", "totinvval")


def _to_bgr(image) -> np.ndarray:
    """Accept a numpy array or a PIL image and hand back something cv2 reads."""
    if isinstance(image, np.ndarray):
        return image
    return np.array(image.convert("RGB"))[:, :, ::-1].copy()


def decode_qr(image) -> str | None:
    """Return the text of the first QR code in the image, or None.

    OpenCV's detector is used rather than a dedicated barcode library because it
    is already a dependency and needs no extra native wheel.  It is tried twice:
    once on the image as given, and once on a doubled copy, since the QR on a
    thermal receipt is often small enough that the finder patterns fall below the
    detector's resolution limit in the original.
    """
    import cv2

    array = _to_bgr(image)
    detector = cv2.QRCodeDetector()

    for candidate in (array, cv2.resize(array, None, fx=2.0, fy=2.0, interpolation=cv2.INTER_CUBIC)):
        try:
            text, points, _ = detector.detectAndDecode(candidate)
        except cv2.error:
            # A malformed or single pixel image makes the detector throw; that is
            # the same outcome as finding nothing, and is treated as such.
            continue
        if text:
            return text
        if points is None:
            continue
    return None


def _b64url_decode(segment: str) -> bytes:
    """Decode one base64url segment, restoring the padding JWS strips."""
    padding = "=" * (-len(segment) % 4)
    return base64.urlsafe_b64decode(segment + padding)


def _jws_payload(raw: str) -> dict | None:
    """Return the decoded JSON payload of a compact JWS, or None.

    Only the middle segment is touched.  Decoding the header would tell us which
    algorithm the issuer claims to have used, and acting on that claim is exactly
    the mistake that makes JWS handling unsafe, so it is left alone.
    """
    parts = raw.strip().split(".")
    if len(parts) != 3 or not all(parts[:2]):
        return None
    try:
        body = _b64url_decode(parts[1])
    except (binascii.Error, ValueError):
        return None
    try:
        parsed = json.loads(body.decode("utf-8", errors="replace"))
    except json.JSONDecodeError:
        return None
    return parsed if isinstance(parsed, dict) else None


def _parse_date(value: object) -> date | None:
    """Read a document date.

    The portal writes dd/mm/yyyy.  Other separators and the ISO ordering turn up
    in supplier generated codes, so each known layout is tried in turn and an
    unrecognised one yields None rather than a wrong date.
    """
    if not value:
        return None
    text = str(value).strip()
    for fmt in ("%d/%m/%Y", "%d-%m-%Y", "%Y-%m-%d", "%d/%m/%y", "%Y/%m/%d"):
        try:
            return datetime.strptime(text, fmt).date()
        except ValueError:
            continue
    return None


def _first(data: dict, keys: tuple[str, ...]) -> object | None:
    for key in keys:
        if key in data and data[key] not in (None, ""):
            return data[key]
    return None


def parse_einvoice_payload(raw: str) -> QRPayload:
    """Read an e-invoice QR string into a QRPayload.

    Three kinds of content are handled.  A compact JWS has its payload segment
    decoded.  A bare JSON object, which some billing software writes directly, is
    read as though it were that payload.  Anything else, a URL or free text,
    yields a payload that holds only the raw string, so the caller can still
    record what was on the paper without any field being invented from it.

    ``signature_verified`` is False in all three cases.  See the module docstring:
    this project has no NIC key material and does not pretend to.
    """
    payload = QRPayload(raw=raw, signature_verified=False)
    if not raw or not isinstance(raw, str):
        return payload

    data = _jws_payload(raw)
    if data is None:
        text = raw.strip()
        if text.startswith("{"):
            try:
                loaded = json.loads(text)
                data = loaded if isinstance(loaded, dict) else None
            except json.JSONDecodeError:
                data = None
    if data is None:
        return payload

    # Some issuers nest the invoice particulars one level down under "data".
    if "data" in data and isinstance(data["data"], dict):
        inner = data["data"]
        if any(key in inner for keys in _FIELD_KEYS.values() for key in keys):
            data = inner
    elif "data" in data and isinstance(data["data"], str) and data["data"].strip().startswith("{"):
        try:
            nested = json.loads(data["data"])
            if isinstance(nested, dict):
                data = nested
        except json.JSONDecodeError:
            pass

    for attr, keys in _FIELD_KEYS.items():
        value = _first(data, keys)
        if value is not None:
            setattr(payload, attr, str(value).strip())

    payload.doc_date = _parse_date(_first(data, _DATE_KEYS))

    total = _first(data, _TOTAL_KEYS)
    if total is not None:
        # The portal writes the invoice value as a decimal string.  It goes
        # through the shared money parser so it becomes integer paise like every
        # other amount in the system, and never a float.
        payload.total_value = parse_money(str(total))

    payload.signature_verified = False
    return payload


def read_einvoice_qr(image) -> QRPayload | None:
    """Decode and parse in one step, or return None when there is no QR."""
    raw = decode_qr(image)
    if raw is None:
        return None
    return parse_einvoice_payload(raw)
